/* eslint-disable @typescript-eslint/no-require-imports -- Standalone CommonJS browser test runner. */
// Optional browser regression suite. Set PLAYWRIGHT_MODULE to an existing
// Playwright installation, or install Playwright in the test environment.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.MINNA_TEST_URL || 'http://127.0.0.1:3000';
const out = path.join(__dirname, '../.cache/minna-qa');
fs.mkdirSync(out, { recursive: true });

(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, serviceWorkers: 'block' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const tab = name => page.locator('.mn-tabs').getByRole('button', { name, exact: true });
    await page.goto(base + '/minna');
    await page.locator('.mn-lesson-card').first().waitFor();
    assert.equal(await page.locator('.mn-lesson-card').count(), 50);
    assert.equal(await page.locator('.mn-lesson-card.unavailable').count(), 1);
    await page.screenshot({ path: path.join(out, 'catalog-desktop.png') });
    await page.getByLabel('Tìm bài học').fill('50');
    assert.equal(await page.locator('.mn-lesson-card').count(), 1);
    await page.goto(base + '/minna/1');
    await tab('Từ vựng').click();
    await page.locator('.mn-word-card').first().waitFor();
    assert.equal(await page.locator('.mn-word-card').count(), 45);
    await page.evaluate(() => localStorage.setItem('kanamaster.progress.v1', JSON.stringify({ sentinel: 'keep-kana-data' })));
    await page.getByLabel('Tìm từ vựng').fill('がくせい');
    assert.equal(await page.locator('.mn-word-card').count(), 1);
    await page.locator('.mn-word-card').getByRole('button', { name: 'Đã nhớ', exact: true }).click();
    await page.reload();
    await tab('Từ vựng').click();
    await page.locator('.mn-word-card.learned').waitFor();
    assert.equal(await page.locator('.mn-word-card.learned').count(), 1);
    await page.screenshot({ path: path.join(out, 'vocabulary-desktop.png') });
    await tab('Flashcard').click();
    await page.getByRole('button', { name: 'Lật thẻ để xem nghĩa' }).click();
    assert.ok((await page.locator('.mn-flashcard').innerText()).includes('Tôi'));
    await page.getByRole('button', { name: 'Cần ôn lại', exact: true }).click();
    assert.ok((await page.locator('.mn-flash-session').innerText()).includes('2 / 45'));
    await tab('Quiz từ vựng').click();
    await page.getByRole('button', { name: 'Bắt đầu quiz', exact: true }).click();
    for (let i = 0; i < 10; i++) {
      await page.locator('.mn-options button').first().click();
      assert.equal(await page.locator('.mn-options button.correct').count(), 1);
      await page.getByRole('button', { name: i === 9 ? 'Xem kết quả' : 'Câu tiếp theo', exact: true }).click();
    }
    await page.locator('.mn-results').waitFor();
    assert.equal(await page.locator('.mn-result-list article').count(), 10);
    const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('kanamaster.minna.v1'))['1']);
    assert.equal(stored.quiz.attempts, 1);
    await page.screenshot({ path: path.join(out, 'quiz-result-desktop.png') });
    if (stored.quiz.wrong.length) {
      await page.getByRole('button', { name: `Ôn lại ${stored.quiz.wrong.length} từ sai`, exact: true }).click();
      assert.ok((await page.locator('.mn-flash-session .mn-pill').innerText()).endsWith(`/ ${stored.quiz.wrong.length}`));
    }
    await tab('Ngữ pháp').click();
    assert.equal(await page.locator('.mn-grammar-card').count(), 5);
    assert.equal(await page.locator('.mn-grammar-card').first().locator('iframe').count(), 1);
    await page.getByRole('button', { name: 'Đánh dấu đã học mục này', exact: true }).first().click();
    await tab('Bài tập').click();
    const exercise = page.locator('.mn-exercise').first();
    assert.equal(await exercise.locator('input').count(), 4);
    const solution = exercise.locator('.mn-solution');
    await solution.locator('summary').click();
    assert.equal(await solution.locator('.mn-solution-answers li').count(), 4);
    assert.match(await solution.innerText(), /Giải thích/);
    assert.ok(await solution.getByRole('button', { name: 'Đối chiếu bài làm' }).isDisabled());
    assert.ok(await page.locator('.mn-practice-body ruby').count() > 0);
    for (const input of await exercise.locator('input').all()) await input.fill('は');
    await solution.getByRole('button', { name: 'Đối chiếu bài làm' }).click();
    assert.equal(await solution.locator('.mn-answer-comparison.matched').count(), 3);
    assert.match(await solution.innerText(), /câu của bạn vẫn có thể đúng/);
    await exercise.locator('input').nth(1).fill('も');
    assert.equal(await solution.locator('.mn-answer-comparison.matched').count(), 4, 'Comparison updates after editing');
    await exercise.getByRole('button', { name: 'Lưu bài làm', exact: true }).click();
    await page.reload();
    await tab('Bài tập').click();
    await page.locator('.mn-exercise').first().getByRole('button', { name: 'Đã lưu bài làm', exact: true }).waitFor();
    assert.equal(await page.locator('.mn-exercise').first().locator('input').first().inputValue(), 'は');
    const persisted = await page.evaluate(() => JSON.parse(localStorage.getItem('kanamaster.minna.v1'))['1']);
    assert.equal(persisted.quiz.attempts, 1);
    assert.equal(persisted.grammar.length, 1);
    assert.ok(persisted.learned.includes('1-word-13'));
    await page.locator('.mn-exercise').first().locator('input').first().fill('も');
    assert.equal(await page.locator('.mn-exercise').first().locator('.green').count(), 0, 'Editing reopens completed exercise');
    const kana = await page.evaluate(() => JSON.parse(localStorage.getItem('kanamaster.progress.v1')));
    assert.equal(kana.sentinel, 'keep-kana-data');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('.mn-exercise').first().locator('.mn-solution > summary').click();
    await page.locator('.mn-exercise').first().scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, 'practice-mobile.png'), fullPage: false });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No horizontal overflow on mobile practice');
    await page.goto(base + '/minna');
    await page.locator('.mn-lesson-card').first().waitFor();
    await page.screenshot({ path: path.join(out, 'catalog-mobile.png') });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No horizontal overflow on catalog');
    await page.setViewportSize({ width: 320, height: 740 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Navigation fits a 320px viewport');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(base + '/minna/39');
    await tab('Quiz từ vựng').click();
    await page.getByRole('heading', { name: 'Chưa có bảng từ vựng trong nguồn' }).waitFor();
    await tab('Bài tập').click();
    assert.ok(await page.locator('.mn-exercise').count() > 0);
    await page.goto(base + '/minna/50');
    await tab('Bài tập').click();
    assert.ok(await page.locator('.mn-exercise').count() > 0);
    await page.goto(base + '/minna/24');
    await tab('Bài tập').click();
    const choice = page.locator('.mn-exercise').first();
    await choice.locator('select').selectOption({ label: 'b.くれました' });
    await choice.locator('.mn-solution > summary').click();
    await choice.getByRole('button', { name: 'Đối chiếu bài làm' }).click();
    assert.equal(await choice.locator('.mn-answer-comparison.matched').count(), 1);
    await page.goto(base + '/minna/9');
    await tab('Bài tập').click();
    await page.locator('.mn-exercise').first().locator('.mn-solution > summary').click();
    assert.match(await page.locator('.mn-exercise').first().innerText(), /Câu trả lời mẫu/);
    await page.goto(base + '/minna/28');
    await tab('Bài tập').click();
    await page.locator('.mn-practice-group').evaluateAll(groups => groups.forEach(g => g.open = true));
    const issue = page.locator('.mn-exercise').filter({ has: page.locator('.mn-solution-issue') }).first();
    assert.equal(await issue.locator('input,select,textarea').count(), 0);
    await issue.locator('.mn-solution > summary').click();
    assert.match(await issue.innerText(), /習慣も違うし/);
    assert.ok(!(await page.locator('.mn-tab-content').innerText()).includes('v:shape'));
    await issue.getByRole('button', { name: 'Đánh dấu đã đọc hướng dẫn' }).click();
    assert.ok(await issue.getByRole('button', { name: 'Đã đọc hướng dẫn', exact: true }).isDisabled());
    await issue.scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, 'solution-source-issue-mobile.png') });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Malformed source stays within mobile width');
    await page.goto(base + '/minna/12');
    await page.getByRole('heading', { name: 'Bài học chưa có dữ liệu' }).waitFor();
    for (const url of ['/learn', '/learn/hiragana-1', '/practice', '/review', '/progress']) {
      const response = await page.goto(base + url);
      assert.equal(response.status(), 200, `Kana route ${url}`);
      await page.getByRole('navigation', { name: 'Main navigation' }).waitFor();
      assert.equal(await page.getByRole('link', { name: 'Minna no Nihongo', exact: true }).count(), 1);
    }
    assert.deepEqual(errors, [], 'No client runtime exceptions');
    await context.close();
    console.log('PASS: browser flows, vocabulary, quiz feedback/results, flashcards, ruby/media, exercise draft persistence, mobile layout, missing data and Kana routes.');
    console.log(`Screenshots: ${out}`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
